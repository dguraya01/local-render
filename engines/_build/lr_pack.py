"""Build, validate and zip local-render packs (the library behind build_pack.py).

  build_pack.py engines                         list engines
  build_pack.py guide <engine>                  print the engine's authoring guide
  build_pack.py init <dir> --engine E --title T [--width 1920 --height 1080 --fps 30 --duration 6]
  build_pack.py finalize <dir>                  fill defaults, add runtime/, run.sh, run.ps1, README.md; validate
  build_pack.py preview <dir> [--time S] [--scale 0.25]   finalize, then render ONE low-res frame
  build_pack.py build <dir> --out pack.zip      finalize, validate, zip

Standard library only.
"""
import argparse
import importlib.util
import json
import os
import shutil
import subprocess
import sys
import zipfile

_HERE = os.path.dirname(os.path.abspath(__file__))


class P:
    ROOT = os.path.dirname(os.path.dirname(_HERE))
    ENGINES = os.path.join(ROOT, "engines")
    RUNTIME = os.path.join(ENGINES, "_runtime")
    SCHEMA = os.path.join(ROOT, "schema", "render.schema.json")


sys.path.insert(0, P.RUNTIME)
import lr_common as C  # noqa: E402
import lr_validate as V  # noqa: E402

MARKER = "<!-- generated by local-render -->"
EXCLUDE_DIRS = {"node_modules", ".lr-work", "__pycache__", ".git", ".venv"}
EXCLUDE_FILES = {".DS_Store", "render-report.json", "Thumbs.db"}
RUNNER = {"tool": "python", "min_version": "3.8", "why": "runs the render script (run.sh / run.ps1)"}


def engines():
    return sorted(d for d in os.listdir(P.ENGINES)
                  if not d.startswith("_") and os.path.isfile(os.path.join(P.ENGINES, d, "adapter.py")))


def load_adapter(engine):
    path = os.path.join(P.ENGINES, engine, "adapter.py")
    if not os.path.isfile(path):
        sys.exit("unknown engine %r. Choose one of: %s" % (engine, ", ".join(engines())))
    spec = importlib.util.spec_from_file_location("adapter_" + engine.replace("-", "_"), path)
    mod = importlib.util.module_from_spec(spec)
    spec.loader.exec_module(mod)
    return mod


def read_manifest(pack):
    with open(os.path.join(pack, "render.json"), encoding="utf-8") as f:
        return json.load(f)


def write_manifest(pack, m):
    order = ["schema_version", "title", "description", "engine", "entry", "output", "resolution", "fps",
             "duration", "codec", "audio", "requires", "dependencies", "render", "engine_options", "generator"]
    out = {k: m[k] for k in order if k in m}
    out.update({k: v for k, v in m.items() if k not in out})
    with open(os.path.join(pack, "render.json"), "w", encoding="utf-8") as f:
        json.dump(out, f, indent=2)
        f.write("\n")


# ------------------------------------------------------------------ init
def cmd_init(a):
    os.makedirs(os.path.join(a.dir, "src"), exist_ok=True)
    os.makedirs(os.path.join(a.dir, "assets"), exist_ok=True)
    if os.path.exists(os.path.join(a.dir, "render.json")):
        sys.exit("render.json already exists in %s" % a.dir)
    entry = {"html-canvas": "src/index.html", "remotion": "src/index.ts", "blender": "src/scene.py",
             "manim": "src/scene.py", "ffmpeg": "src/slideshow.json"}[a.engine]
    slug = "".join(ch if ch.isalnum() else "-" for ch in a.title.lower()).strip("-")[:60] or "video"
    m = {"schema_version": "1.0", "title": a.title, "engine": a.engine, "entry": entry,
         "output": slug + ".mp4", "resolution": {"width": a.width, "height": a.height},
         "fps": a.fps, "duration": a.duration, "codec": "h264"}
    write_manifest(a.dir, m)
    print("created %s/render.json. Now write %s (see: build_pack.py guide %s)" % (a.dir, entry, a.engine))


# ------------------------------------------------------------------ finalize
def copy_runtime(pack, engine, adapter):
    rt = os.path.join(pack, "runtime")
    keep_nm = os.path.join(rt, "node_modules")
    if os.path.isdir(rt):
        for name in os.listdir(rt):
            p = os.path.join(rt, name)
            if p != keep_nm:
                shutil.rmtree(p) if os.path.isdir(p) else os.remove(p)
    os.makedirs(rt, exist_ok=True)
    for name in ("lr_render.py", "lr_common.py", "lr_validate.py"):
        shutil.copy2(os.path.join(P.RUNTIME, name), rt)
    shutil.copy2(P.SCHEMA, os.path.join(rt, "render.schema.json"))
    shutil.copy2(os.path.join(P.ENGINES, engine, "adapter.py"), os.path.join(rt, "adapter.py"))
    for name in getattr(adapter, "RUNTIME_FILES", []):
        shutil.copy2(os.path.join(P.ENGINES, engine, name), rt)


def fill_defaults(pack, m, adapter):
    m.setdefault("schema_version", "1.0")
    m.setdefault("codec", "h264")
    reqs = [r for r in m.get("requires", []) if isinstance(r, dict) and "tool" in r]
    have = {r["tool"] for r in reqs}
    for r in [RUNNER] + list(adapter.REQUIRES):
        if r["tool"] not in have:
            reqs.append(dict(r))
            have.add(r["tool"])
    if m["engine"] in ("html-canvas", "blender", "manim", "ffmpeg") and "ffprobe" not in have:
        reqs.append({"tool": "ffprobe", "min_version": "4.4", "why": "reads the finished video for the report"})
    m["requires"] = reqs
    deps = m.get("dependencies") or json.loads(json.dumps(getattr(adapter, "DEPENDENCIES", {})))
    npm_dir = deps.get("npm_dir")
    if npm_dir and os.path.isfile(os.path.join(pack, npm_dir, "package.json")):
        with open(os.path.join(pack, npm_dir, "package.json"), encoding="utf-8") as f:
            pj = json.load(f)
        deps["npm"] = dict(pj.get("dependencies") or {})
    if deps:
        m["dependencies"] = deps
    else:
        m.pop("dependencies", None)
    m["render"] = {"command": "sh run.sh",
                   "windows_command": "powershell -ExecutionPolicy Bypass -File run.ps1",
                   "engine_command": adapter.engine_command(m)}
    m["generator"] = {"name": "local-render", "version": C.VERSION}
    return m


def safe_comment(s):
    return "".join(ch for ch in s if ch.isprintable() and ch not in "\"'`$\\")[:120]


RUN_SH = """#!/bin/sh
# local-render: renders "{title}" on this computer.
# Usage:  sh run.sh            render the video
#         sh run.sh --check    only check that the needed tools are installed
#         sh run.sh --preview  render one small test frame (preview.png)
# All the work happens in runtime/lr_render.py (plain Python, standard library only).
cd "$(dirname "$0")" || exit 1
for PY in python3 python; do
  if command -v "$PY" >/dev/null 2>&1 && "$PY" -c 'import sys; sys.exit(0 if sys.version_info >= (3, 8) else 1)' >/dev/null 2>&1; then
    exec "$PY" -I runtime/lr_render.py "$@"
  fi
done
echo "Python 3.8 or newer is needed to render this video."
echo "  macOS:  brew install python   (or https://www.python.org/downloads/)"
echo "  Linux:  sudo apt install python3"
exit 1
"""

RUN_PS1 = """# local-render: renders "{title}" on this computer.
# Usage:  powershell -ExecutionPolicy Bypass -File run.ps1 [--check | --preview]
# All the work happens in runtime/lr_render.py (plain Python, standard library only).
$ErrorActionPreference = "Continue"
Set-Location -Path $PSScriptRoot
$candidates = @(@("py", "-3"), @("python"), @("python3"))
foreach ($c in $candidates) {{
  $exe = $c[0]
  $pre = @($c | Select-Object -Skip 1)
  if (Get-Command $exe -ErrorAction SilentlyContinue) {{
    & $exe @pre -c "import sys; sys.exit(0 if sys.version_info >= (3, 8) else 1)" *> $null
    if ($LASTEXITCODE -eq 0) {{
      & $exe @pre -I runtime/lr_render.py @args
      exit $LASTEXITCODE
    }}
  }}
}}
Write-Host "Python 3.8 or newer is needed to render this video."
Write-Host "  Install it with:  winget install --id Python.Python.3.12 -e"
Write-Host "  or download it from https://www.python.org/downloads/"
exit 1
"""


def readme(m):
    w, h = m["resolution"]["width"], m["resolution"]["height"]
    tools = [r for r in m["requires"] if r["tool"] != "ffprobe"]
    rows = []
    for r in tools:
        ins = C.TOOLS[r["tool"]]["install"]
        need = (" %s or newer" % r["min_version"]) if r.get("min_version") else ""
        rows.append("| %s%s | `%s` | `%s` |" % (r["tool"], need, ins["mac"], ins["windows"]))
    return """{marker}
# {title}

{desc}This folder is a **render pack**: everything needed to turn code into a video on
your own computer. Rendering here takes a minute or two instead of most of an hour in the cloud.

**Video:** {w}x{h}, {fps} fps, {dur} seconds, made with **{engine}**. The finished file is `{out}`.

## Render it with Claude Code (easiest)

Open Claude Code in the folder that holds this pack and say:

> Render this video pack.

Claude checks your computer, shows you what will run, and asks before running or installing anything.

## Render it yourself

1. Open a terminal in this folder.
   - **Mac:** right-click the folder in Finder → *New Terminal at Folder*.
   - **Windows:** open the folder, click the address bar, type `powershell`, press Enter.
2. Run one command:
   - **Mac / Linux:** `sh run.sh`
   - **Windows:** `powershell -ExecutionPolicy Bypass -File run.ps1`
3. When it finishes, `{out}` appears in this folder.

The script prints what is missing if a tool isn't installed. Run `sh run.sh --check`
first if you only want to check.

## What you need

| Tool | Mac | Windows |
|---|---|---|
{rows}

## If something goes wrong

- **"command not found" / missing tool:** install the tool from the table above, close and reopen the terminal, run again.
- **First run is slow:** it downloads packages (into this folder only). Later runs are fast.
- **Force the safe software encoder:** `sh run.sh --encoder libx264`.

## What's inside

| Path | What it is |
|---|---|
| `render.json` | Settings: size, length, engine, and the exact render command |
| `src/` | The animation's source code |
| `assets/` | Images, fonts and audio it uses |
| `runtime/` | The local-render script that runs the engine and encodes the video |
| `run.sh`, `run.ps1` | One-command render scripts |
""".format(marker=MARKER, title=m["title"], desc=(m["description"].strip() + "\n\n") if m.get("description") else "",
           w=w, h=h, fps=m["fps"], dur=m["duration"], engine=m["engine"], out=m["output"], rows="\n".join(rows))


def cmd_finalize(a, quiet=False):
    pack = os.path.abspath(a.dir)
    m = read_manifest(pack)
    engine = m.get("engine")
    adapter = load_adapter(engine)
    copy_runtime(pack, engine, adapter)
    m = fill_defaults(pack, m, adapter)
    write_manifest(pack, m)
    title = safe_comment(m.get("title", "video"))
    for name, tpl in (("run.sh", RUN_SH), ("run.ps1", RUN_PS1)):
        with open(os.path.join(pack, name), "w", encoding="utf-8", newline="\n") as f:
            f.write(tpl.format(title=title))
    os.chmod(os.path.join(pack, "run.sh"), 0o755)
    rp = os.path.join(pack, "README.md")
    existing = ""
    if os.path.exists(rp):
        with open(rp, encoding="utf-8") as f:
            existing = f.read()
    if not existing or existing.startswith(MARKER):
        with open(rp, "w", encoding="utf-8") as f:
            f.write(readme(m))
    for d in ("src", "assets"):
        os.makedirs(os.path.join(pack, d), exist_ok=True)
    _, errs = V.validate_pack(pack)
    if errs:
        print("pack is NOT valid:")
        for e in errs:
            print("  - " + e)
        sys.exit(1)
    if not quiet:
        print("finalized and valid: %s" % pack)
    return pack, m


# ------------------------------------------------------------------ preview / build
def cmd_preview(a):
    pack, m = cmd_finalize(a, quiet=True)
    cmd = [sys.executable, os.path.join(pack, "runtime", "lr_render.py"), "--preview", "--scale", str(a.scale)]
    if a.time is not None:
        cmd += ["--time", str(a.time)]
    code = subprocess.call(cmd, cwd=pack)
    if code != 0:
        print("preview could not be rendered here (exit %d). That's fine: the pack can still be "
              "built and rendered on the user's machine." % code)
    return code


def iter_files(pack, out_name):
    for dirpath, dirnames, filenames in os.walk(pack):
        dirnames[:] = sorted(d for d in dirnames if d not in EXCLUDE_DIRS and not d.startswith(".lr"))
        for fn in sorted(filenames):
            if fn in EXCLUDE_FILES or fn == out_name or fn.endswith((".pyc", ".zip")):
                continue
            full = os.path.join(dirpath, fn)
            if os.path.islink(full):
                continue
            yield full, os.path.relpath(full, pack).replace(os.sep, "/")


def cmd_build(a):
    pack, m = cmd_finalize(a, quiet=True)
    out = os.path.abspath(a.out)
    os.makedirs(os.path.dirname(out), exist_ok=True)
    total = 0
    with zipfile.ZipFile(out, "w", zipfile.ZIP_DEFLATED, compresslevel=9) as z:
        for full, rel in iter_files(pack, m["output"]):
            zi = zipfile.ZipInfo.from_file(full, rel)
            zi.compress_type = zipfile.ZIP_DEFLATED
            mode = 0o755 if rel == "run.sh" else 0o644
            zi.external_attr = (0o100000 | mode) << 16
            with open(full, "rb") as f:
                data = f.read()
            total += len(data)
            z.writestr(zi, data)
    size = os.path.getsize(out)
    print("built %s (%s, %d files, %s uncompressed)" % (out, C.human_size(size), len(z.namelist()), C.human_size(total)))
    if size > 100 * 2 ** 20:
        print("warning: pack is over 100 MB. Consider compressing assets.")
    return out


def main():
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    sub = ap.add_subparsers(dest="cmd", required=True)
    sub.add_parser("engines")
    g = sub.add_parser("guide")
    g.add_argument("engine")
    i = sub.add_parser("init")
    i.add_argument("dir")
    i.add_argument("--engine", required=True, choices=engines())
    i.add_argument("--title", required=True)
    i.add_argument("--width", type=int, default=1920)
    i.add_argument("--height", type=int, default=1080)
    i.add_argument("--fps", type=float, default=30)
    i.add_argument("--duration", type=float, default=6)
    f = sub.add_parser("finalize")
    f.add_argument("dir")
    p = sub.add_parser("preview")
    p.add_argument("dir")
    p.add_argument("--time", type=float)
    p.add_argument("--scale", type=float, default=0.25)
    b = sub.add_parser("build")
    b.add_argument("dir")
    b.add_argument("--out", required=True)
    a = ap.parse_args()
    if a.cmd == "engines":
        for e in engines():
            doc = " ".join((load_adapter(e).__doc__ or "").split())
            print("%-12s %s" % (e, doc.split(". ")[0].split(": ", 1)[-1].rstrip(".")))
    elif a.cmd == "guide":
        path = os.path.join(P.ENGINES, a.engine, "AUTHORING.md")
        if not os.path.isfile(path):
            sys.exit("no guide for %r. Engines: %s" % (a.engine, ", ".join(engines())))
        with open(path, encoding="utf-8") as f:
            print(f.read())
    elif a.cmd == "init":
        cmd_init(a)
    elif a.cmd == "finalize":
        cmd_finalize(a)
    elif a.cmd == "preview":
        sys.exit(cmd_preview(a))
    elif a.cmd == "build":
        cmd_build(a)


if __name__ == "__main__":
    main()
